// Turns `Ty` into TypeScript source text.

import { isIdent, isNumericKey } from "./ident.ts";
import type { Prop, Ty, View } from "./ty.ts";

export const HEADER = "// Generated by kanagata. Do not edit.\n";

/** Context precedence. A type binding looser than its context is parenthesized. */
export const Prec = { Union: 0, Inter: 1, Postfix: 2 } as const;
export type Prec = (typeof Prec)[keyof typeof Prec];

/** The declared name of a view of a component schema. */
export type Namer = (schema: string, view: View) => string;

export class Out {
	buf = "";
	depth = 0;
	readonly #name: Namer;

	constructor(name: Namer) {
		this.#name = name;
	}

	ty(t: Ty, ctx: Prec): void {
		switch (t.kind) {
			case "unknown":
			case "never":
			case "null":
			case "undefined":
			case "string":
			case "number":
			case "boolean":
				this.buf += t.kind;
				break;
			case "integer":
				this.buf += "number";
				break;
			case "blob":
				this.buf += "Blob";
				break;
			case "record":
				this.buf += "Record<string, unknown>";
				break;
			case "lit":
				this.buf += t.text;
				break;
			case "ref":
				this.buf += this.#name(t.schema, t.view);
				break;
			case "opRef":
				this.buf += `operations[${JSON.stringify(t.id)}]`;
				break;
			case "array":
				this.ty(t.elem, Prec.Postfix);
				this.buf += "[]";
				break;
			case "tuple":
				this.buf += "[";
				t.items.forEach((item, i) => {
					if (i > 0) this.buf += ", ";
					if (i < t.min) {
						this.ty(item, Prec.Union);
					} else {
						this.ty(item, Prec.Postfix);
						this.buf += "?";
					}
				});
				if (t.rest !== undefined) {
					if (t.items.length > 0) this.buf += ", ";
					this.buf += "...";
					this.ty(t.rest, Prec.Postfix);
					this.buf += "[]";
				}
				this.buf += "]";
				break;
			case "object":
				this.object(t.props);
				break;
			case "map":
				this.object(t.props, t.index);
				break;
			case "union":
				this.list(t.items, " | ", ctx > Prec.Union, Prec.Union);
				break;
			case "inter":
				this.list(t.items, " & ", ctx > Prec.Inter, Prec.Inter);
				break;
		}
	}

	private list(items: Ty[], sep: string, paren: boolean, inner: Prec): void {
		if (paren) this.buf += "(";
		items.forEach((item, i) => {
			if (i > 0) this.buf += sep;
			this.ty(item, inner);
		});
		if (paren) this.buf += ")";
	}

	object(props: Prop[], index?: Ty): void {
		if (props.length === 0 && index === undefined) {
			this.buf += "{}";
			return;
		}
		this.buf += "{\n";
		this.depth++;
		for (const p of props) {
			if (p.doc !== undefined) this.doc(p.doc);
			this.indent();
			this.key(p.key);
			if (p.optional) this.buf += "?";
			this.buf += ": ";
			this.ty(p.ty, Prec.Union);
			this.buf += ";\n";
		}
		if (index !== undefined) {
			this.indent();
			this.buf += "[key: string]: ";
			this.ty(index, Prec.Union);
			this.buf += ";\n";
		}
		this.depth--;
		this.indent();
		this.buf += "}";
	}

	private indent(): void {
		this.buf += "  ".repeat(this.depth);
	}

	/** Writes a property key: bare if it is an identifier or a canonical integer, otherwise as a JSON string. */
	key(k: string): void {
		this.buf += isIdent(k) || isNumericKey(k) ? k : JSON.stringify(k);
	}

	/** Writes a JSDoc comment on its own line(s) at the current indentation. */
	doc(d: string): void {
		const lines = d
			.replaceAll("*/", "*\\/")
			.split("\n")
			.map((l) => l.trimEnd());
		if (lines.length === 1) {
			this.indent();
			this.buf += `/** ${lines[0]} */\n`;
			return;
		}
		this.indent();
		this.buf += "/**\n";
		for (const line of lines) {
			this.indent();
			this.buf += line === "" ? " *\n" : ` * ${line}\n`;
		}
		this.indent();
		this.buf += " */\n";
	}
}

/** A named type declaration: `export type <name> = <ty>;` */
export interface Decl {
	name: string;
	ty: Ty;
	doc?: string;
}

/** Everything the generator emits. */
export interface Document {
	paths: Prop[];
	/** Emitted only when the document has webhooks. */
	webhooks?: Prop[];
	operations: Prop[];
	/** Schema name → its declared type. */
	schemas: Prop[];
	decls: Decl[];
}

export function render(doc: Document, name: Namer): string {
	const out = new Out(name);
	out.buf += HEADER;
	const interfaces: [string, Prop[]][] = [["paths", doc.paths]];
	if (doc.webhooks !== undefined) interfaces.push(["webhooks", doc.webhooks]);
	interfaces.push(["operations", doc.operations], ["schemas", doc.schemas]);
	for (const [name, props] of interfaces) {
		out.buf += `\nexport interface ${name} `;
		out.object(props);
		out.buf += "\n";
	}
	for (const decl of doc.decls) {
		out.buf += "\n";
		if (decl.doc !== undefined) out.doc(decl.doc);
		out.buf += `export type ${decl.name} = `;
		out.ty(decl.ty, Prec.Union);
		out.buf += ";\n";
	}
	return out.buf;
}
