/** Generated declarations and the warnings raised on the way. */
export interface Generated {
	code: string;
	warnings: Diag[];
}

/** Where the document is, so that `$ref`s to other files can be followed. */
export interface Source {
	/** The document's absolute URL, such as a `file:` URL; relative `$ref`s resolve against it. Any other string is an `input` GenerateError. */
	url: string;
	/** The text of the document at an absolute URL; throws, with a message saying why, when it cannot be read. */
	read: (url: string) => string;
}

/** How the document is read, and what the output's first line says. */
export interface Options {
	/**
	 * In 3.0, read `nullable: true` as "this schema or null": `null` even without `type`,
	 * next to `$ref`, and past an `enum`, `const` or `allOf` that does not admit it.
	 * Off by default: `nullable` adds `null` to `type` only, as OpenAPI 3.0.3 says.
	 */
	looseNullable?: boolean;
	/**
	 * The kanagata version the first line names (`// Generated by kanagata 0.4.0. Do not edit.`),
	 * as the CLI writes it. Without it, the line names no version.
	 */
	version?: string;
}

/** Text that starts with `{` (or is blank) is JSON; anything else is YAML. */
function parseText(src: string, warnings: Diag[]): Value {
	return /^﻿?\s*(\{|$)/.test(src) ? parse(src) : parseYaml(src, warnings);
}

/**
 * Converts an OpenAPI document (JSON or YAML) to a `.d.ts` file. With a `source`,
 * `$ref`s to other files are read through it. Throws GenerateError.
 */
export function generate(
	src: string,
	source?: Source,
	options: Options = {},
): Generated {
	if (source !== undefined) checkSource(source.url);
	const read: Diag[] = [];
	const root = parseText(src, read);
	if (!(root instanceof JsonObject))
		throw new DiagError("#", "an OpenAPI document is an object");
	checkVersion(root);

	const s = get(root.get("components"), "schemas");
	if (s !== undefined && !(s instanceof JsonObject)) {
		throw new DiagError("#/components/schemas", "schemas must be an object");
	}
	const schemas = s?.entries ?? [];
	const cx: Ctx = new Ctx(
		root,
		new Set(schemas.map(([k]) => k)),
		// 3.1 and 3.2 Schema Objects are JSON Schema 2020-12.
		!(root.get("openapi") as string).startsWith("3.0."),
		source && {
			url: source.url,
			load: (url) => loadText(cx, url, source.read(url)),
		},
		options.looseNullable === true,
	);

	// The default $schema of the document's schemas (3.1, 3.2).
	const dialect = root.get("jsonSchemaDialect");
	if (cx.refSiblings && dialect !== undefined)
		readDialect("#/jsonSchemaDialect", dialect);

	// Whether what is built meets a reference in an intersection (see `refKinds`).
	const meeting = <T>(build: () => T): [T, boolean] => {
		const before = refsMet();
		const built = build();
		return [built, refsMet() !== before];
	};
	const [p, pathsMet] = meeting(() => paths(cx, root));

	// Every component schema, then every schema from another file that got a key (the
	// list grows as they are converted), named, in both views; the write view gets its
	// own declaration only where the two differ (readOnly / writeOnly here or in a reference).
	const converted: Converted[] = schemas.map(([key, value]) => {
		const at = child("#/components/schemas", key);
		const [[read, write], met] = meeting(() => [
			cx.inMode("read", () => schema(cx, value, at)),
			cx.inMode("write", () => schema(cx, value, at)),
		]);
		return { key, value, at, read, write, met };
	});
	for (let i = 0; i < cx.hoisted.length; i++) {
		const { key, value, base, where } = cx.hoisted[i] as Hoisted;
		const view = (mode: View) =>
			cx.withBase(base, () => cx.inMode(mode, () => schema(cx, value, where)));
		const [[read, write], met] = meeting(() => [view("read"), view("write")]);
		converted.push({ key, value, at: where, read, write, met });
	}
	rejectBareCycles(converted);
	// Which kinds a reference admits is its component's type's, known once all of them
	// are converted: what those kinds rule out is left out of the intersections that met
	// it, in the types built with one.
	const kinds = refKinds(converted);
	const kinded = (t: Ty) => (pathsMet ? kinds(t) : t);
	const names = typeNames(converted.map((c) => c.key));
	// typeNames gives one name per key, in order
	const components: Component[] = converted.map((c, i) => ({
		...c,
		...(c.met ? { read: kinds(c.read), write: kinds(c.write) } : {}),
		name: names[i] as string,
	}));
	const differing = differingViews(components);
	// An operation reached again is declared once, so its types must be declared alike:
	// a reference to either view of a schema without a second type is the same name.
	for (const a of p.again)
		if (!equal(kinded(a.first.ty), kinded(a.ty), differing))
			throw new DiagError(
				a.at,
				`operation ${JSON.stringify(a.id)} is also ${a.first.at}, where its type differs; operations[${JSON.stringify(a.id)}] has one type`,
			);
	const withInput = components.filter((c) => differing.has(c.key));
	const inputs = inputNames(
		withInput.map((c) => c.name),
		names,
	);
	const readName = new Map(components.map((c) => [c.key, c.name]));
	const writeName = new Map(
		withInput.map((c, j) => [c.key, inputs[j] as string]),
	);
	const name = (key: string, view: View) =>
		(view === "write" ? writeName.get(key) : undefined) ??
		(readName.get(key) as string);

	// Whether a type admits any value can depend on the components it refers to, so keys
	// a JSON object must have get `{} | null` once all of them are converted.
	const present = presentIn(components);
	const decls: Decl[] = [];
	const index: Prop[] = [];
	for (const c of components) {
		const d = schemaDoc(cx, c.value);
		const decl = (n: string, ty: Ty): Decl =>
			d === undefined ? { name: n, ty } : { name: n, ty, doc: d };
		index.push(prop(c.key, ref(c.key)));
		decls.push(decl(c.name, present(c.read)));
		const w = writeName.get(c.key);
		if (w !== undefined) decls.push(decl(w, present(c.write)));
	}
	const props = (ps: Prop[]) =>
		ps.map((q) => ({ ...q, ty: present(kinded(q.ty)) }));
	const ops = {
		paths: props(p.paths),
		operations: props(p.operations),
		...(p.webhooks === undefined ? {} : { webhooks: props(p.webhooks) }),
	};

	const code = render({ ...ops, schemas: index, decls }, name, options.version);
	return { code, warnings: [...read, ...cx.warnings] };
}

/**
 * Accepts a source URL that `$ref`s can resolve against and messages can name files by: an
 * absolute URL whose percent-encoding decodes. Anything else is an input error.
 */
function checkSource(url: string): void {
	if (!URL.canParse(url))
		throw new GenerateError(
			"input",
			`source.url is not an absolute URL: ${url}`,
		);
	if (!decodes(url))
		throw new GenerateError(
			"input",
			`source.url has a malformed percent-encoding: ${url}`,
		);
}

/** Parses another document; its problems are located in that file (`defs/a.yaml:3:1`, `defs/a.yaml#/b`). */
function loadText(cx: Ctx, url: string, text: string): Value {
	const file = cx.where(url);
	const warnings: Diag[] = [];
	try {
		const doc = parseText(text, warnings);
		for (const w of warnings) cx.warn(`${file}${w.at}`, w.msg);
		return doc;
	} catch (e) {
		// The parsers throw only syntax errors, located by line and column.
		const err = e as GenerateError;
		throw new GenerateError(err.kind, `${file}:${err.message}`);
	}
}

interface Converted {
	key: string;
	value: Value;
	/** Where it is defined, for messages. */
	at: string;
	read: Ty;
	write: Ty;
	/** Whether its views met a reference in an intersection (`refsMet`). */
	met: boolean;
}

interface Component extends Converted {
	name: string;
}

/**
 * Rejects a schema that reaches itself through unions, intersections and references
 * only (`Tree: { oneOf: [{ type: string }, { $ref: Tree }] }`): TypeScript rejects
 * `type Tree = string | Tree` (TS2456). A reference inside an object, array or tuple
 * type is deferred, so a cycle through one is a type. Each view is checked: one can
 * leave out what breaks a cycle in the other (an `allOf` member that is `never` in one).
 */
function rejectBareCycles(converted: readonly Converted[]): void {
	const byKey = new Map(converted.map((c) => [c.key, c]));
	const done = new Set<string>();
	const path: string[] = [];
	const visit = (key: string, view: View): void => {
		const id = `${view} ${key}`;
		const start = path.indexOf(id);
		if (start >= 0) {
			const cycle = [...path.slice(start), id]
				.map((p) => p.slice(view.length + 1))
				.join(" → ");
			const sent = view === "write" ? ", in what is sent to the API" : "";
			throw new DiagError(
				(byKey.get(key) as Converted).at,
				`circular reference without an object, array or tuple in between, which TypeScript rejects${sent}: ${cycle}`,
			);
		}
		if (done.has(id)) return;
		path.push(id);
		for (const r of bareRefs((byKey.get(key) as Converted)[view]))
			visit(r.schema, r.view);
		path.pop();
		done.add(id);
	};
	for (const c of converted) visit(c.key, "read");
	for (const c of converted) visit(c.key, "write");
}

/**
 * `withRefKinds`, each reference's component its type in the reference's view, of the
 * kinds read with those of the references in it (`kindsWith`). A component reaches none
 * of them again through unions, intersections and references alone (`rejectBareCycles`).
 */
function refKinds(converted: readonly Converted[]): (t: Ty) => Ty {
	const byKey = new Map(converted.map((c) => [c.key, c]));
	const type = ({ schema, view }: RefTy): Ty =>
		(byKey.get(schema) as Converted)[view];
	const known = new Map<string, ValueKind[] | undefined>();
	const of = (r: RefTy): ValueKind[] | undefined => {
		const id = `${r.view} ${r.schema}`;
		if (known.has(id)) return known.get(id);
		const kinds = kindsWith(type(r), of);
		known.set(id, kinds);
		return kinds;
	};
	const done = [new Map<Ty, Ty>(), new Map<Ty, Ty>()] as const;
	return (t) => withRefKinds(t, { kinds: of, type }, done);
}

/** `presentKeys`, with references resolved to the components' types in their view. */
function presentIn(components: readonly Component[]): (t: Ty) => Ty {
	const byKey = new Map(components.map((c) => [c.key, c]));
	const known = new Map<string, boolean>();
	const any = (t: Ty): boolean =>
		admitsAny(t, ({ schema, view }) => {
			const id = `${view} ${schema}`;
			const seen = known.get(id);
			if (seen !== undefined) return seen;
			// A component that reaches itself is an object, array or tuple, not any value.
			known.set(id, false);
			const c = byKey.get(schema) as Component;
			const result = any(view === "write" ? c.write : c.read);
			known.set(id, result);
			return result;
		});
	return (t) => presentKeys(t, any);
}

/**
 * The schemas whose read and write views differ: in their own conversion (ignoring
 * which view their references point to), or through a schema they reference.
 */
function differingViews(components: readonly Component[]): Set<string> {
	const differing = new Set(
		components.filter((c) => !equal(c.read, c.write, false)).map((c) => c.key),
	);
	const referrers = new Map<string, string[]>();
	for (const c of components)
		for (const r of refs(c.write)) {
			const list = referrers.get(r) ?? [];
			list.push(c.key);
			referrers.set(r, list);
		}
	// The closure over "is referred to by": a Set's iteration visits what is added during it.
	for (const key of differing)
		for (const r of referrers.get(key) ?? []) differing.add(r);
	return differing;
}

function checkVersion(root: JsonObject): void {
	const v = root.get("openapi");
	if (typeof v === "string") {
		if (v.startsWith("3.0.") || v.startsWith("3.1.") || v.startsWith("3.2."))
			return;
		throw new DiagError(
			"#/openapi",
			`unsupported OpenAPI version ${JSON.stringify(v)} (3.0.x, 3.1.x or 3.2.x required)`,
		);
	}
	if (v !== undefined)
		throw new DiagError("#/openapi", "openapi must be a string");
	if (root.get("swagger") !== undefined) {
		throw new DiagError(
			"#/swagger",
			"Swagger 2.0 is not supported (convert it to OpenAPI 3.x first)",
		);
	}
	throw new DiagError("#", "missing openapi version field");
}
