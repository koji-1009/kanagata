// The executable, as a user runs it: arguments in, exit code and output out.
// Behaviour is covered in process by cli.test.ts; this checks the wiring.

import assert from "node:assert/strict";
import { spawn, spawnSync } from "node:child_process";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { test } from "vitest";

const ROOT = join(import.meta.dirname, "..");
const BIN = join(ROOT, "src", "bin.ts");
const BASIC = join(ROOT, "tests", "spec", "basic");

test("generate prints the declarations, stamped with the package's version, and exits 0", () => {
	const out = spawnSync(
		process.execPath,
		[BIN, "generate", join(BASIC, "input.json")],
		{ encoding: "utf8" },
	);
	const { version } = JSON.parse(
		readFileSync(join(ROOT, "package.json"), "utf8"),
	);
	assert.equal(out.status, 0);
	assert.equal(
		out.stdout,
		readFileSync(join(BASIC, "expected.d.ts"), "utf8").replace(
			"// Generated by kanagata.",
			`// Generated by kanagata ${version}.`,
		),
	);
	assert.equal(out.stderr, "");
});

test("an error goes to stderr with exit code 2", () => {
	const out = spawnSync(
		process.execPath,
		[BIN, "generate", "does-not-exist.json"],
		{ encoding: "utf8" },
	);
	assert.equal(out.status, 2);
	assert.equal(out.stderr, "does-not-exist.json: no such file or directory\n");
});

test("a stdout nobody reads exits 2", async () => {
	const child = spawn(
		process.execPath,
		[BIN, "generate", join(BASIC, "input.json")],
		{
			stdio: ["ignore", "pipe", "pipe"],
		},
	);
	child.stdout.destroy();
	let stderr = "";
	child.stderr.setEncoding("utf8").on("data", (d: string) => {
		stderr += d;
	});
	const status = await new Promise<number | null>((resolve) =>
		child.on("close", resolve),
	);
	assert.equal(status, 2);
	assert.match(stderr, /^stdout: \S/);
});
